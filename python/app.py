#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""AutoOpenApps - 软件启动助手

用法：
  AutoOpenApps.exe            管理界面（浏览器打开）：维护软件清单、一键启动、开机自启开关
  AutoOpenApps.exe --auto     开机模式：弹出“启动确认”页面，勾选要打开的软件后确认启动

配置： %APPDATA%\\AutoOpenApps\\config.json
开机自启： 启动文件夹\\AutoOpenApps.bat  ->  start "" "本exe" --auto
"""
import json
import os
import socket
import subprocess
import sys
import threading
import time
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

import ui

APP_NAME = "AutoOpenApps"
DONE = threading.Event()
STATE = {"cfg": {"apps": []}, "server": None, "started": time.time(),
         "last_ping": time.time(), "auto": False}


# ---------- paths & config ----------

def config_dir():
    return os.path.join(os.environ.get("APPDATA", os.path.expanduser("~")), APP_NAME)


def config_file():
    return os.path.join(config_dir(), "config.json")


def load_config():
    try:
        with open(config_file(), "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, dict) and isinstance(data.get("apps"), list):
            apps = []
            for a in data["apps"]:
                if not isinstance(a, dict) or not a.get("path"):
                    continue
                apps.append({
                    "name": str(a.get("name") or os.path.basename(str(a.get("path")))),
                    "path": str(a.get("path")),
                    "delay": max(0, min(300, int(a.get("delay") or 0))),
                    "args": str(a.get("args") or ""),
                    "enabled": bool(a.get("enabled", True)),
                })
            return {"apps": apps}
    except Exception:
        pass
    return {"apps": []}


def save_config(cfg):
    os.makedirs(config_dir(), exist_ok=True)
    with open(config_file(), "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)


# ---------- autostart (startup folder bat) ----------

def startup_dir():
    base = os.environ.get("APPDATA", os.path.expanduser("~"))
    return os.path.join(base, "Microsoft", "Windows", "Start Menu", "Programs", "Startup")


def bat_path():
    return os.path.join(startup_dir(), "AutoOpenApps.bat")


def autostart_installed():
    try:
        with open(bat_path(), "r", encoding="utf-8", errors="ignore") as f:
            return "--auto" in f.read()
    except Exception:
        return False


def set_autostart(enable):
    if enable:
        if not getattr(sys, "frozen", False):
            return {"ok": False, "message": "开发模式下不支持开机自启：请先用 PyInstaller 打包成 exe 再开启。"}
        exe = sys.executable
        if " " in exe:
            pass  # quoted below anyway
        content = ("@echo off\r\n"
                   "rem AutoOpenApps boot launcher (generated by 软件启动助手)\r\n"
                   'start "" "{0}" --auto\r\n').format(exe)
        try:
            os.makedirs(startup_dir(), exist_ok=True)
            with open(bat_path(), "w", encoding="ascii", errors="ignore") as f:
                f.write(content)
            return {"ok": True, "message": "已开启开机自启：开机登录后会弹出确认页，勾选后再打开软件。"}
        except Exception as e:
            return {"ok": False, "message": "写入启动文件夹失败：%s" % e}
    else:
        try:
            if os.path.exists(bat_path()):
                os.remove(bat_path())
            return {"ok": True, "message": "已关闭开机自启（启动脚本已删除）。"}
        except Exception as e:
            return {"ok": False, "message": "删除启动脚本失败：%s" % e}


# ---------- launching ----------

def is_running(exe_path):
    name = os.path.basename(exe_path)
    if not name:
        return False
    try:
        out = subprocess.run(["tasklist", "/FI", "IMAGENAME eq {0}".format(name)],
                             capture_output=True, text=True, timeout=10).stdout or ""
        return name.lower() in out.lower()
    except Exception:
        return False


def launch_apps(items):
    launched, skipped, failed = [], [], []
    for it in items:
        name = it.get("name") or os.path.basename(it.get("path", ""))
        try:
            delay = int(it.get("delay") or 0)
        except Exception:
            delay = 0
        if delay > 0:
            time.sleep(min(delay, 300))
        p = (it.get("path") or "").strip()
        if not p or not os.path.exists(p):
            failed.append([name, "路径不存在"])
            continue
        if is_running(p):
            skipped.append(name)
            continue
        args = (it.get("args") or "").strip()
        try:
            cmd = [p] + (args.split() if args else [])
            subprocess.Popen(cmd, close_fds=True)
            launched.append(name)
        except Exception as e:
            failed.append([name, str(e)])
        time.sleep(0.4)
    return {"launched": launched, "skipped": skipped, "failed": failed}


# ---------- native file dialog (comdlg32) ----------

def native_open_dialog():
    try:
        import ctypes
        from ctypes import wintypes

        class OPENFILENAME(ctypes.Structure):
            _fields_ = [
                ("lStructSize", wintypes.DWORD), ("hwndOwner", wintypes.HWND),
                ("hInstance", wintypes.HINSTANCE), ("lpstrFilter", wintypes.LPCWSTR),
                ("lpstrCustomFilter", wintypes.LPWSTR), ("nMaxCustFilter", wintypes.DWORD),
                ("nFilterIndex", wintypes.DWORD), ("lpstrFile", wintypes.LPWSTR),
                ("nMaxFile", wintypes.DWORD), ("lpstrFileTitle", wintypes.LPWSTR),
                ("nMaxFileTitle", wintypes.DWORD), ("lpstrInitialDir", wintypes.LPCWSTR),
                ("lpstrTitle", wintypes.LPCWSTR), ("Flags", wintypes.DWORD),
                ("nFileOffset", wintypes.WORD), ("nFileExtension", wintypes.WORD),
                ("lpstrDefExt", wintypes.LPCWSTR), ("lCustData", wintypes.LPARAM),
                ("lpfnHook", wintypes.LPVOID), ("lpTemplateName", wintypes.LPCWSTR),
            ]

        buf = ctypes.create_unicode_buffer(260)
        ofn = OPENFILENAME()
        ofn.lStructSize = ctypes.sizeof(OPENFILENAME)
        ofn.lpstrFilter = "程序文件 (*.exe;*.lnk;*.bat)\0*.exe;*.lnk;*.bat\0所有文件 (*.*)\0*.*\0"
        ofn.lpstrFile = ctypes.cast(buf, wintypes.LPWSTR)
        ofn.nMaxFile = 260
        ofn.lpstrTitle = "选择要启动的程序"
        ofn.Flags = 0x00080000 | 0x00001000 | 0x00000008  # OFN_EXPLORER|OFN_FILEMUSTEXIST|OFN_PATHMUSTEXIST
        if ctypes.windll.comdlg32.GetOpenFileNameW(ctypes.byref(ofn)):
            return buf.value
    except Exception:
        pass
    return ""


# ---------- http server ----------

class Handler(BaseHTTPRequestHandler):
    server_version = "AutoOpenApps/1.0"

    def log_message(self, fmt, *args):  # silence
        pass

    def _json(self, obj, code=200):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _html(self, text):
        body = text.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _body(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0:
            return {}
        try:
            return json.loads(self.rfile.read(length).decode("utf-8"))
        except Exception:
            return {}

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path == "/api/ping":
            STATE["last_ping"] = time.time()
            return self._json({"ok": True})
        if path == "/api/config":
            STATE["last_ping"] = time.time()
            return self._json({"apps": STATE["cfg"].get("apps", []),
                               "autostart": autostart_installed(),
                               "configFile": config_file()})
        if path == "/confirm" and STATE["auto"]:
            return self._html(ui.confirm_page())
        if path == "/" and not STATE["auto"]:
            return self._html(ui.manager_page(config_file()))
        return self._json({"error": "not found"}, 404)

    def do_POST(self):
        path = self.path.split("?", 1)[0]
        data = self._body()
        if path == "/api/config":
            apps = data.get("apps")
            if isinstance(apps, list):
                STATE["cfg"] = {"apps": apps}
                try:
                    save_config(STATE["cfg"])
                    return self._json({"ok": True})
                except Exception as e:
                    return self._json({"ok": False, "error": str(e)}, 500)
            return self._json({"ok": False, "error": "bad request"}, 400)
        if path == "/api/launch":
            apps = STATE["cfg"].get("apps", [])
            if data.get("all"):
                items = [a for a in apps if a.get("enabled")]
            else:
                wanted = set(data.get("paths") or [])
                items = [a for a in apps if a.get("path") in wanted]
            return self._json(launch_apps(items))
        if path == "/api/autostart":
            return self._json(set_autostart(bool(data.get("enable"))))
        if path == "/api/browse":
            return self._json({"path": native_open_dialog()})
        if path == "/api/cancel":
            return self._json({"ok": True, "message": "已取消。"})
        if path == "/api/shutdown":
            DONE.set()
            return self._json({"ok": True})
        return self._json({"error": "not found"}, 404)


def watchdog():
    """Exit the process ~2 minutes after the browser tab stops responding."""
    while not DONE.is_set():
        time.sleep(5)
        if time.time() - STATE["started"] > 20 and time.time() - STATE["last_ping"] > 120:
            DONE.set()


def main():
    STATE["auto"] = "--auto" in sys.argv
    STATE["cfg"] = load_config()
    try:
        srv = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    except Exception:
        srv = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    STATE["server"] = srv
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    threading.Thread(target=watchdog, daemon=True).start()
    port = srv.server_address[1]
    url = "http://127.0.0.1:{0}{1}".format(port, "/confirm" if STATE["auto"] else "/")
    print("AutoOpenApps URL: {0}".format(url), flush=True)
    if os.environ.get("AUTOOPENAPPS_NO_BROWSER") != "1":
        threading.Thread(target=webbrowser.open, args=(url,), daemon=True).start()
    DONE.wait()
    try:
        srv.shutdown()
    except Exception:
        pass


if __name__ == "__main__":
    main()
